const EARTH_RADIUS_M = 6371008.8;

/**
 * Great-circle distance in metres. Deliberately a different formula from the
 * equirectangular offsets under test, so a bug in the offset model cannot
 * cancel itself out in the assertion.
 */
export function distanceMetres(a: [number, number], b: [number, number]): number {
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b[0] - a[0]);
  const dLon = toRad(b[1] - a[1]);
  const h =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLon / 2) ** 2;
  return 2 * EARTH_RADIUS_M * Math.asin(Math.min(1, Math.sqrt(h)));
}
